export function tr(lang: Lang, key: string): string {
  const e = D[key]
  return e ? (e[lang] ?? e.fa) : key
}

export function tf(lang: Lang, key: string, n: number): string {
  return tr(lang, key).replace('{n}', String(n))
}

export interface TFunc {
  (key: string): string
  fmt: (key: string, n: number) => string
}

export function useT(lang: Lang): TFunc {
  const t = ((key: string) => tr(lang, key)) as TFunc
  t.fmt = (key: string, n: number) => tf(lang, key, n)
  return t
}

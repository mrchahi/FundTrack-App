const daysAgo = (d: number) => new Date(now.getTime() - d * 86400 * 1000).toISOString();
const daysAgoWithHour = (d: number, hour: number, durationMin: number) => {
  const close = new Date(now);
  close.setDate(close.getDate() - d);
  close.setHours(hour, 15, 0, 0);
  const open = new Date(close.getTime() - durationMin * 60000);
  return { openTime: open.toISOString(), closeTime: close.toISOString() };
};
